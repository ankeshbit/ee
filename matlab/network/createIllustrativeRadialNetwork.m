function network = createIllustrativeRadialNetwork()
% createIllustrativeRadialNetwork Create a small educational radial network.
% All impedances are per-unit on the network base. Values are illustrative
% assumptions for software verification, not validated engineering data.

network.base = struct('SbaseVA', 10e6, 'VbaseV', 11e3);
network.sourceBus = 'SOURCE';
network.source = struct( ...
    'Vth_pu', 1, ...
    'Z1_pu', 0.1, ...
    'Z2_pu', 0.1, ...
    'Z0_pu', 0.1);
network.buses = struct( ...
    'id', {'SOURCE', 'BUS_A', 'BUS_B'}, ...
    'VbaseV', {11e3, 11e3, 11e3});
network.branches = struct( ...
    'id', {'BR_A', 'BR_B'}, ...
    'fromBus', {'SOURCE', 'BUS_A'}, ...
    'toBus', {'BUS_A', 'BUS_B'}, ...
    'Z1_pu', {0.05, 0.05}, ...
    'Z2_pu', {0.05, 0.05}, ...
    'Z0_pu', {0.15, 0.15});
end

function network = createIllustrativeRadialNetwork()
% createIllustrativeRadialNetwork Create a small educational radial network.
% All parameters are sourced from matlab/config/getSystemMasterConfiguration.m
% ensuring complete traceability and single-source consistency.

cfg = getSystemMasterConfiguration();

network.base = struct('SbaseVA', cfg.systemBase.SbaseVA.value, 'VbaseV', cfg.systemBase.VbaseLV_V.value);
network.sourceBus = 'SOURCE';
network.source = struct( ...
    'Vth_pu', cfg.source.Vth_pu.value, ...
    'Z1_pu', cfg.source.Z1_pu.value, ...
    'Z2_pu', cfg.source.Z2_pu.value, ...
    'Z0_pu', cfg.source.Z0_pu.value);
network.buses = struct( ...
    'id', {'SOURCE', 'BUS_A', 'BUS_B'}, ...
    'VbaseV', {cfg.systemBase.VbaseLV_V.value, cfg.systemBase.VbaseLV_V.value, cfg.systemBase.VbaseLV_V.value});
network.branches = struct( ...
    'id', {'BR_A', 'BR_B'}, ...
    'fromBus', {'SOURCE', 'BUS_A'}, ...
    'toBus', {'BUS_A', 'BUS_B'}, ...
    'Z1_pu', {cfg.feeders.BRA.Z1_pu.value, cfg.feeders.BRB.Z1_pu.value}, ...
    'Z2_pu', {cfg.feeders.BRA.Z2_pu.value, cfg.feeders.BRB.Z2_pu.value}, ...
    'Z0_pu', {cfg.feeders.BRA.Z0_pu.value, cfg.feeders.BRB.Z0_pu.value});
end

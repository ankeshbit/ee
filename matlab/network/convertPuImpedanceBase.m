function ZpuNew = convertPuImpedanceBase( ...
    ZpuOld, SbaseOldVA, VbaseOldV, SbaseNewVA, VbaseNewV)
% convertPuImpedanceBase Convert per-unit impedance between compatible bases.
% Voltage bases must refer to the same physical side of a transformer.
%
% ZpuNew = ZpuOld * (SbaseNewVA/SbaseOldVA) * ...
%     (VbaseOldV/VbaseNewV)^2

validateattributes(ZpuOld, {'numeric'}, {'scalar', 'finite'});
validateattributes(SbaseOldVA, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(VbaseOldV, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(SbaseNewVA, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(VbaseNewV, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});

ZpuNew = ZpuOld * (SbaseNewVA / SbaseOldVA) * ...
    (VbaseOldV / VbaseNewV)^2;
end

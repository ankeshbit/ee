function validateTransformerConfiguration(transformer, busIds)
% validateTransformerConfiguration Validate an explicit transformer model.
% Supported zero-sequence modes:
%   grounded-wye-grounded-wye: passes configured Z0_pu.
%   delta-grounded-wye: blocks zero-sequence transfer through the transformer.

if ~isstruct(transformer) || ~isscalar(transformer)
    error('validateTransformerConfiguration:InvalidTransformer', ...
        'Transformer must be a scalar structure.');
end
requiredFields = {'id', 'highVoltageBus', 'lowVoltageBus', ...
    'ratedHighVoltageV', 'ratedLowVoltageV', 'ratedSbaseVA', ...
    'Z1_pu', 'Z2_pu', 'Z0_pu', 'windingConnection', 'grounding'};
for index = 1:numel(requiredFields)
    if ~isfield(transformer, requiredFields{index})
        error('validateTransformerConfiguration:MissingField', ...
            'Transformer is missing required field %s.', requiredFields{index});
    end
end
if isfield(transformer, 'phaseShift_deg') && ...
        (~isnumeric(transformer.phaseShift_deg) || ...
        ~isscalar(transformer.phaseShift_deg) || ...
        ~isfinite(transformer.phaseShift_deg))
    error('validateTransformerConfiguration:InvalidPhaseShift', ...
        'phaseShift_deg must be a finite numeric scalar when supplied.');
end
if isfield(transformer, 'vectorGroup') && ...
        (~ischar(transformer.vectorGroup) || ...
        ~isrow(transformer.vectorGroup) || ...
        isempty(strtrim(transformer.vectorGroup)))
    error('validateTransformerConfiguration:InvalidVectorGroup', ...
        'vectorGroup must be a nonempty character vector when supplied.');
end
if (isfield(transformer, 'phaseShift_deg') && ...
        abs(transformer.phaseShift_deg) > 0) || ...
        (isfield(transformer, 'vectorGroup') && ...
        ~any(strcmpi(strtrim(transformer.vectorGroup), ...
        {'Yy0', 'grounded-wye-grounded-wye'})))
    error('validateTransformerConfiguration:UnsupportedPhaseShift', ...
        'Configured transformer phase displacement/vector group is unsupported.');
end
validateattributes(transformer.ratedHighVoltageV, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(transformer.ratedLowVoltageV, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(transformer.ratedSbaseVA, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
for field = {'Z1_pu', 'Z2_pu', 'Z0_pu'}
    value = transformer.(field{1});
    if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value)
        error('validateTransformerConfiguration:InvalidImpedance', ...
            'Transformer %s must be a finite numeric scalar.', field{1});
    end
end
if ~any(strcmp(busIds, transformer.highVoltageBus)) || ...
        ~any(strcmp(busIds, transformer.lowVoltageBus)) || ...
        strcmp(transformer.highVoltageBus, transformer.lowVoltageBus)
    error('validateTransformerConfiguration:InvalidTerminal', ...
        'Transformer terminals must be distinct configured buses.');
end
connection = lower(strtrim(transformer.windingConnection));
supported = {'grounded-wye-grounded-wye', 'delta-grounded-wye'};
if ~any(strcmp(connection, supported))
    error('validateTransformerConfiguration:UnsupportedWindingConnection', ...
        'Unsupported transformer winding connection: %s.', connection);
end
if ~ischar(transformer.grounding) || isempty(strtrim(transformer.grounding))
    error('validateTransformerConfiguration:InvalidGrounding', ...
        'Transformer grounding must be explicitly configured.');
end
if strcmp(connection, 'grounded-wye-grounded-wye') && ...
        ~strcmpi(strtrim(transformer.grounding), 'both neutrals grounded')
    error('validateTransformerConfiguration:UnsupportedGrounding', ...
        'Grounded-wye-grounded-wye requires both neutrals grounded.');
end
end

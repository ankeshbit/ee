function config = createRadialRelayStudyConfiguration()
% createRadialRelayStudyConfiguration Create documented relay protection settings
% and coordination parameters for the 33/11 kV radial fault study network.
%
% Topology:
%   SOURCE (33 kV) -> Transformer T1 (33/11 kV, 10 MVA) -> Feeder BRA (11 kV)
%   -> Bus A (11 kV) -> Feeder BRB (11 kV) -> Bus B (11 kV) -> Load (1 MW)
%
% Design Assumptions & Illustrative Settings:
%   - System Base: 10 MVA, 11 kV base at Bus B (Ibase = 524.86 A), 33 kV at Source (Ibase = 174.95 A).
%   - Normal Load Current: 1 MW at 11 kV = 52.49 A primary (Bus A, Bus B); 17.50 A primary (33 kV).
%   - Units: All pickupCurrent_A values are specified in CT secondary amperes.
%   - Relay Curves: IEC Standard Inverse (SI), IEC Very Inverse (VI), IEC Extremely Inverse (EI).
%   - Breaker Delays: Realistic 5-cycle (50 ms) to 4-cycle (80 ms) opening delays.
%   - Coordination Criteria: Minimum CTI = 0.250 s between Bus B and Bus A.
%
% Output:
%   config - Struct containing:
%            relays             : Array of relay configuration structs
%            breakers           : Array of circuit breaker configuration structs
%            coordinationPairs  : Array of primary/backup coordination pair structs
%            zones              : Array of protection zone definitions
%            network            : Network reference structure
%            criteria           : Coordination and margin criteria

    % 1. Network reference structure
    network.base = struct('SbaseVA', 10e6, 'VbaseV', 33e3);
    network.sourceBus = 'SOURCE_33KV';
    network.buses = struct( ...
        'id', {'SOURCE_33KV', 'BUS_A', 'BUS_B'}, ...
        'VbaseV', {33e3, 11e3, 11e3});
    network.transformers = struct( ...
        'id', 'T1', ...
        'highVoltageBus', 'SOURCE_33KV', ...
        'lowVoltageBus', 'BUS_A', ...
        'ratedHighVoltageV', 33e3, ...
        'ratedLowVoltageV', 11e3, ...
        'ratedSbaseVA', 10e6, ...
        'Z1_pu', 0.08, 'Z2_pu', 0.08, 'Z0_pu', 0.08, ...
        'windingConnection', 'grounded-wye-grounded-wye', ...
        'grounding', 'both neutrals grounded');
    network.branches = struct( ...
        'id', {'FEEDER_BRA', 'FEEDER_BRB'}, ...
        'fromBus', {'BUS_A', 'BUS_A'}, ...
        'toBus', {'BUS_A', 'BUS_B'}, ...
        'Z1_pu', {0.05, 0.05}, ...
        'Z2_pu', {0.05, 0.05}, ...
        'Z0_pu', {0.15, 0.15});

    % 2. Relay Definitions
    % Relay 1: Downstream Feeder / Bus B Relay
    % CT: 400/5 A (Ratio = 80). Pickup = 1.0 A sec (80 A pri).
    % Healthy load = 52.49 A pri -> 0.656 A sec (< 1.0 A -> no trip).
    relays(1).id = 'RELAY_BUS_B';
    relays(1).name = 'Bus B Feeder Overcurrent Relay';
    relays(1).locationBus = 'BUS_B';
    relays(1).voltageLevel_V = 11e3;
    relays(1).CTprimary_A = 400;
    relays(1).CTsecondary_A = 5;
    relays(1).pickupCurrent_A = 1.0; % CT Secondary Amperes
    relays(1).TMS = 0.10;
    relays(1).curveType = 'Standard Inverse';
    relays(1).breakerId = 'CB_BUS_B';
    relays(1).protectedBranch = 'FEEDER_BRB';
    relays(1).measurementElementType = 'branch';
    relays(1).measurementElementId = 'FEEDER_BRB';
    relays(1).measurementSide = 'toBus';
    relays(1).directionalSettings = struct( ...
        'enabled', false, ...
        'characteristicAngle_deg', 45);

    % Relay 2: Bus A Substation Feeder Relay (Backup to Relay Bus B)
    % CT: 600/5 A (Ratio = 120). Pickup = 1.0 A sec (120 A pri).
    % Healthy load = 52.49 A pri -> 0.4375 A sec (< 1.0 A -> no trip).
    relays(2).id = 'RELAY_BUS_A';
    relays(2).name = 'Bus A Feeder Overcurrent Relay';
    relays(2).locationBus = 'BUS_A';
    relays(2).voltageLevel_V = 11e3;
    relays(2).CTprimary_A = 600;
    relays(2).CTsecondary_A = 5;
    relays(2).pickupCurrent_A = 1.0; % CT Secondary Amperes
    relays(2).TMS = 0.25;
    relays(2).curveType = 'Standard Inverse';
    relays(2).breakerId = 'CB_BUS_A';
    relays(2).protectedBranch = 'FEEDER_BRB';
    relays(2).measurementElementType = 'branch';
    relays(2).measurementElementId = 'FEEDER_BRB';
    relays(2).measurementSide = 'fromBus';
    relays(2).directionalSettings = struct( ...
        'enabled', false, ...
        'characteristicAngle_deg', 45);

    % Relay 3: 33 kV Transformer HV Overcurrent Relay (Remote Backup)
    % CT: 200/5 A (Ratio = 40). Pickup = 1.5 A sec (60 A pri at 33 kV -> 180 A at 11 kV).
    % Healthy load = 17.50 A pri at 33 kV -> 0.4375 A sec (< 1.5 A -> no trip).
    relays(3).id = 'RELAY_33KV';
    relays(3).name = '33 kV Transformer HV Incomer Relay';
    relays(3).locationBus = 'SOURCE_33KV';
    relays(3).voltageLevel_V = 33e3;
    relays(3).CTprimary_A = 200;
    relays(3).CTsecondary_A = 5;
    relays(3).pickupCurrent_A = 1.5; % CT Secondary Amperes
    relays(3).TMS = 0.40;
    relays(3).curveType = 'Standard Inverse';
    relays(3).breakerId = 'CB_33KV';
    relays(3).protectedBranch = 'T1';
    relays(3).measurementElementType = 'transformer';
    relays(3).measurementElementId = 'T1';
    relays(3).measurementSide = 'highVoltageBus';
    relays(3).directionalSettings = struct( ...
        'enabled', false, ...
        'characteristicAngle_deg', 45);

    % 3. Circuit Breaker Definitions
    breakers(1) = struct( ...
        'id', 'CB_BUS_B', ...
        'relayId', 'RELAY_BUS_B', ...
        'openingDelay_s', 0.050, ... % 50 ms (2.5 cycles at 50 Hz)
        'state', 'closed', ...
        'canClear', true);

    breakers(2) = struct( ...
        'id', 'CB_BUS_A', ...
        'relayId', 'RELAY_BUS_A', ...
        'openingDelay_s', 0.060, ... % 60 ms (3 cycles at 50 Hz)
        'state', 'closed', ...
        'canClear', true);

    breakers(3) = struct( ...
        'id', 'CB_33KV', ...
        'relayId', 'RELAY_33KV', ...
        'openingDelay_s', 0.080, ... % 80 ms (4 cycles at 50 Hz)
        'state', 'closed', ...
        'canClear', true);

    % 4. Primary/Backup Coordination Pairs
    coordinationPairs(1) = struct( ...
        'pairId', 'PAIR_B_A', ...
        'primaryRelayId', 'RELAY_BUS_B', ...
        'backupRelayId', 'RELAY_BUS_A', ...
        'minimumCTI_s', 0.250, ...
        'minimumMargin_s', 0.190);

    coordinationPairs(2) = struct( ...
        'pairId', 'PAIR_A_33KV', ...
        'primaryRelayId', 'RELAY_BUS_A', ...
        'backupRelayId', 'RELAY_33KV', ...
        'minimumCTI_s', 0.300, ...
        'minimumMargin_s', 0.220);

    % 5. Protection Zones (Conforming to validateProtectionZones)
    zones(1) = struct( ...
        'id', 'ZONE_FEEDER_BRB', ...
        'protectedElementType', 'branch', ...
        'protectedElementId', 'FEEDER_BRB', ...
        'applicableFaultedBuses', {{'BUS_B'}}, ...
        'primaryRelayId', 'RELAY_BUS_B', ...
        'backupRelayIds', {{'RELAY_BUS_A', 'RELAY_33KV'}}, ...
        'breakerId', 'CB_BUS_B', ...
        'minimumCTI_s', 0.250);

    zones(2) = struct( ...
        'id', 'ZONE_TRANSFORMER_T1', ...
        'protectedElementType', 'transformer', ...
        'protectedElementId', 'T1', ...
        'applicableFaultedBuses', {{'BUS_A'}}, ...
        'primaryRelayId', 'RELAY_BUS_A', ...
        'backupRelayIds', {{'RELAY_33KV'}}, ...
        'breakerId', 'CB_BUS_A', ...
        'minimumCTI_s', 0.300);

    % 6. Study Criteria
    criteria = struct( ...
        'standardMinCTI_s', 0.250, ...
        'standardMinMargin_s', 0.200, ...
        'maxPrimaryOperatingTime_s', 1.000, ...
        'loadSecurityMarginFactor', 1.30);

    config.network = network;
    config.relays = relays;
    config.breakers = breakers;
    config.coordinationPairs = coordinationPairs;
    config.zones = zones;
    config.criteria = criteria;
end

function config = createRadialRelayStudyConfiguration()
% createRadialRelayStudyConfiguration Create documented relay protection settings
% and coordination parameters for the 33/11 kV radial fault study network.
%
% All parameters are sourced from matlab/config/getSystemMasterConfiguration.m
% guaranteeing single-source consistency across analytical engines, model builders,
% and test suites.

    cfg = getSystemMasterConfiguration();

    % 1. Network reference structure
    network.base = struct('SbaseVA', cfg.systemBase.SbaseVA.value, 'VbaseV', cfg.systemBase.VbaseHV_V.value);
    network.sourceBus = cfg.source.id;
    network.source = struct( ...
        'Vth_pu', cfg.source.Vth_pu.value, ...
        'Z1_pu', cfg.source.Z1_pu.value, ...
        'Z2_pu', cfg.source.Z2_pu.value, ...
        'Z0_pu', cfg.source.Z0_pu.value);
    network.buses = struct( ...
        'id', {cfg.source.id, 'BUS_11KV', 'BUS_A', 'BUS_B'}, ...
        'VbaseV', {cfg.systemBase.VbaseHV_V.value, cfg.systemBase.VbaseLV_V.value, cfg.systemBase.VbaseLV_V.value, cfg.systemBase.VbaseLV_V.value});
    network.transformers = struct( ...
        'id', cfg.transformer.id, ...
        'highVoltageBus', cfg.transformer.highVoltageBus, ...
        'lowVoltageBus', cfg.transformer.lowVoltageBus, ...
        'ratedHighVoltageV', cfg.transformer.ratedHighVoltageV.value, ...
        'ratedLowVoltageV', cfg.transformer.ratedLowVoltageV.value, ...
        'ratedSbaseVA', cfg.transformer.ratedSbaseVA.value, ...
        'Z1_pu', cfg.transformer.Z1_pu.value, ...
        'Z2_pu', cfg.transformer.Z2_pu.value, ...
        'Z0_pu', cfg.transformer.Z0_pu.value, ...
        'windingConnection', cfg.transformer.windingConnection, ...
        'grounding', cfg.transformer.grounding);
    network.branches = struct( ...
        'id', {cfg.feeders.BRA.id, cfg.feeders.BRB.id}, ...
        'fromBus', {cfg.feeders.BRA.fromBus, cfg.feeders.BRB.fromBus}, ...
        'toBus', {cfg.feeders.BRA.toBus, cfg.feeders.BRB.toBus}, ...
        'Z1_pu', {cfg.feeders.BRA.Z1_pu.value, cfg.feeders.BRB.Z1_pu.value}, ...
        'Z2_pu', {cfg.feeders.BRA.Z2_pu.value, cfg.feeders.BRB.Z2_pu.value}, ...
        'Z0_pu', {cfg.feeders.BRA.Z0_pu.value, cfg.feeders.BRB.Z0_pu.value});

    % 2. Relay Definitions (unwrapped from master config struct)
    numRelays = numel(cfg.relays);
    relays = repmat(struct(), 1, numRelays);
    for ri = 1:numRelays
        r = cfg.relays(ri);
        relays(ri).id = r.id;
        relays(ri).name = r.name;
        relays(ri).locationBus = r.locationBus;
        relays(ri).voltageLevel_V = r.voltageLevel_V.value;
        relays(ri).CTprimary_A = r.CTprimary_A.value;
        relays(ri).CTsecondary_A = r.CTsecondary_A.value;
        relays(ri).pickupCurrent_A = r.pickupCurrent_A.value;
        relays(ri).TMS = r.TMS.value;
        relays(ri).curveType = r.curveType;
        relays(ri).breakerId = r.breakerId;
        relays(ri).protectedBranch = r.protectedBranch;
        relays(ri).measurementElementType = r.measurementElementType;
        relays(ri).measurementElementId = r.measurementElementId;
        relays(ri).measurementSide = r.measurementSide;
        relays(ri).directionalSettings = r.directionalSettings;
    end

    % 3. Circuit Breaker Definitions
    numBreakers = numel(cfg.breakers);
    breakers = repmat(struct(), 1, numBreakers);
    for bi = 1:numBreakers
        b = cfg.breakers(bi);
        breakers(bi).id = b.id;
        breakers(bi).relayId = cfg.relays(bi).id;
        breakers(bi).openingDelay_s = b.openingDelay_s.value;
        breakers(bi).state = 'closed';
        breakers(bi).canClear = true;
    end

    % 4. Primary/Backup Coordination Pairs
    coordinationPairs(1) = struct( ...
        'pairId', 'PAIR_B_A', ...
        'primaryRelayId', 'RELAY_BUS_B', ...
        'backupRelayId', 'RELAY_BUS_A', ...
        'applicableFaultedBuses', {{'BUS_B'}}, ...
        'minimumCTI_s', cfg.coordinationCriteria.minCTI_s.value, ...
        'minimumMargin_s', cfg.coordinationCriteria.minMarginFeeder_s.value);

    coordinationPairs(2) = struct( ...
        'pairId', 'PAIR_A_33KV', ...
        'primaryRelayId', 'RELAY_BUS_A', ...
        'backupRelayId', 'RELAY_33KV', ...
        'applicableFaultedBuses', {{'BUS_B'}}, ...
        'minimumCTI_s', cfg.coordinationCriteria.minCTITransformer_s.value, ...
        'minimumMargin_s', cfg.coordinationCriteria.minMarginTransformer_s.value);

    % 5. Protection Zones
    zones(1) = struct( ...
        'id', 'ZONE_FEEDER_BRB', ...
        'protectedElementType', 'branch', ...
        'protectedElementId', 'FEEDER_BRB', ...
        'applicableFaultedBuses', {{'BUS_B'}}, ...
        'primaryRelayId', 'RELAY_BUS_B', ...
        'backupRelayIds', {{'RELAY_BUS_A', 'RELAY_33KV'}}, ...
        'breakerId', 'CB_BUS_B', ...
        'minimumCTI_s', cfg.coordinationCriteria.minCTI_s.value);

    zones(2) = struct( ...
        'id', 'ZONE_TRANSFORMER_T1', ...
        'protectedElementType', 'transformer', ...
        'protectedElementId', 'T1', ...
        'applicableFaultedBuses', {{'BUS_11KV'}}, ...
        'primaryRelayId', 'RELAY_33KV', ...
        'backupRelayIds', {{}}, ...
        'breakerId', 'CB_33KV', ...
        'minimumCTI_s', cfg.coordinationCriteria.minCTITransformer_s.value);

    zones(3) = struct( ...
        'id', 'ZONE_FEEDER_BRA', ...
        'protectedElementType', 'branch', ...
        'protectedElementId', 'FEEDER_BRA', ...
        'applicableFaultedBuses', {{'BUS_A'}}, ...
        'primaryRelayId', 'RELAY_33KV', ...
        'backupRelayIds', {{}}, ...
        'breakerId', 'CB_33KV', ...
        'minimumCTI_s', cfg.coordinationCriteria.minCTI_s.value);

    % 6. Study Criteria
    criteria = struct( ...
        'standardMinCTI_s', cfg.coordinationCriteria.minCTI_s.value, ...
        'standardMinMargin_s', cfg.coordinationCriteria.standardMinMargin_s.value, ...
        'maxPrimaryOperatingTime_s', 1.000, ...
        'loadSecurityMarginFactor', 1.30);

    config.network = network;
    config.relays = relays;
    config.breakers = breakers;
    config.coordinationPairs = coordinationPairs;
    config.zones = zones;
    config.criteria = criteria;
    config.masterConfig = cfg;
end

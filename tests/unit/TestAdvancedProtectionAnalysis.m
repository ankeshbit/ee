classdef TestAdvancedProtectionAnalysis < matlab.unittest.TestCase

    methods (Test)

        function testBreakerDelayIsSeparate(testCase)
            result = calculateBreakerClearingTime(2.5, 0.15);
            testCase.verifyEqual(result.relayOperatingTime_s, 2.5);
            testCase.verifyEqual(result.breakerOpeningDelay_s, 0.15);
            testCase.verifyEqual(result.totalClearingTime_s, 2.65, ...
                'AbsTol', 1e-12);
        end

        function testNonOperatingRelayClearingTimeRemainsInfinite(testCase)
            result = calculateBreakerClearingTime(Inf, 0.2);
            testCase.verifyTrue(isinf(result.totalClearingTime_s));
        end

        function testInvalidBreakerDelay(testCase)
            testCase.verifyError( ...
                @() calculateBreakerClearingTime(1, -0.1), ...
                'MATLAB:expectedNonnegative');
        end

        function testCTScreeningStates(testCase)
            relay = relayConfig();
            within = screenCTSaturation(400, relay, 6);
            exceeds = screenCTSaturation(800, relay, 6);
            missing = screenCTSaturation(400, relay);
            testCase.verifyEqual(within.status, 'withinConfiguredLimits');
            testCase.verifyEqual(exceeds.status, 'exceedsConfiguredThreshold');
            testCase.verifyEqual(missing.status, 'insufficientData');
        end

        function testDirectionalUnsupportedWithoutPhasors(testCase)
            result = evaluateDirectionalSupervision(struct('enabled', true), ...
                struct());
            testCase.verifyEqual(result.status, 'unsupported');
        end

        function testDirectionalForwardAndReversePhasors(testCase)
            settings = struct('enabled', true, ...
                'characteristicAngle_deg', 0);
            forward = evaluateDirectionalSupervision(settings, struct( ...
                'currentPhasor', 1, 'polarizingVoltagePhasor', 1));
            reverse = evaluateDirectionalSupervision(settings, struct( ...
                'currentPhasor', -1, 'polarizingVoltagePhasor', 1));
            testCase.verifyEqual(forward.status, 'forward');
            testCase.verifyEqual(reverse.status, 'reverse');
        end

        function testProtectionZoneValidation(testCase)
            network = createIllustrativeBranchedTransformerRadialNetwork();
            relays = relaysForStudy();
            breakers = struct('id', 'CB_B', 'relayId', 'R_B', ...
                'openingDelay_s', 0.1);
            zone = struct('id', 'ZONE_B', ...
                'protectedElementType', 'branch', ...
                'protectedElementId', 'BR_2', ...
                'primaryRelayId', 'R_B', ...
                'backupRelayIds', {{'R_1'}}, ...
                'minimumCTI_s', 0.2, 'breakerId', 'CB_B');
            testCase.verifyWarningFree(@() validateProtectionZones( ...
                zone, network, relays, breakers));
            zone.primaryRelayId = 'UNKNOWN';
            testCase.verifyError(@() validateProtectionZones( ...
                zone, network, relays, breakers), ...
                'validateProtectionZones:InvalidRelayReference');
        end

        function testSensitivityAndReport(testCase)
            network = createIllustrativeBranchedTransformerRadialNetwork();
            scenarios = [ ...
                scenario('B_3PH', 'BUS_B', 'three phase', 0), ...
                scenario('C_3PH', 'BUS_C', 'three phase', 0.1)];
            relays = relaysForStudy();
            pairs = struct('primaryRelayId', 'R_B', ...
                'backupRelayId', 'R_1', 'minimumCTI_s', 0);
            options.breakers = struct( ...
                'id', {'CB_B', 'CB_1'}, ...
                'relayId', {'R_B', 'R_1'}, ...
                'openingDelay_s', {0.1, 0.2});
            options.ctScreeningThresholds.R_B = 8;
            study = runFaultSensitivityStudy( ...
                network, scenarios, relays, pairs, options);
            report = generateFaultSensitivityReport(study);
            testCase.verifyEqual(height(study.relayTable), ...
                numel(scenarios) * numel(relays));
            testCase.verifyEqual(height(report.scenarioSummary), 2);
            testCase.verifyEqual( ...
                report.coordination.primaryTotalClearingTime_s(1), ...
                study.relayTable.totalClearingTime_s( ...
                strcmp(study.relayTable.relayId, 'R_B') & ...
                strcmp(study.relayTable.scenarioId, 'B_3PH')), ...
                'AbsTol', 1e-12);
        end
    end
end

function relay = relayConfig()
relay = struct('CTprimary_A', 400, 'CTsecondary_A', 5);
end

function values = relaysForStudy()
values = struct( ...
    'id', {'R_1', 'R_B'}, ...
    'measurementElementType', {'branch', 'branch'}, ...
    'measurementElementId', {'BR_1', 'BR_2'}, ...
    'measurementSide', {'from', 'from'}, ...
    'pickupCurrent_A', {2, 2}, 'TMS', {1, 1}, ...
    'curveType', {'Very Inverse', 'Very Inverse'}, ...
    'CTprimary_A', {800, 400}, 'CTsecondary_A', {5, 5});
end

function value = scenario(id, bus, type, impedance)
value = struct('id', id, 'faultedBus', bus, ...
    'faultType', type, 'Zf_pu', impedance);
end

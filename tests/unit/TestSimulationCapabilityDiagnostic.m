classdef TestSimulationCapabilityDiagnostic < matlab.unittest.TestCase
% TestSimulationCapabilityDiagnostic Unit tests for checkSimulationCapabilities.

    methods (Test)

        function testDefaultEnvironmentAudit(testCase)
            options = struct('quiet', true);
            diag = checkSimulationCapabilities(options);

            % Verify presence of all schema fields
            testCase.verifyNotEmpty(diag.matlabRelease);
            testCase.verifyNotEmpty(diag.matlabVersion);
            testCase.verifyNotEmpty(diag.operatingSystem);
            testCase.verifyTrue(islogical(diag.simulinkInstalled));
            testCase.verifyTrue(islogical(diag.simulinkLicensed));
            testCase.verifyTrue(islogical(diag.simscapeInstalled));
            testCase.verifyTrue(islogical(diag.simscapeLicensed));
            testCase.verifyTrue(islogical(diag.simscapeElectricalInstalled));
            testCase.verifyTrue(islogical(diag.simscapeElectricalLicensed));
            testCase.verifyTrue(islogical(diag.modelBuildingAPIsAvailable));
            testCase.verifyTrue(islogical(diag.simulationAPIsAvailable));
            testCase.verifyTrue(iscell(diag.satisfiedRequirements));
            testCase.verifyTrue(iscell(diag.missingRequirements));
            testCase.verifyTrue(iscell(diag.unverifiedRequirements));

            % In the current environment, Simulink and Simscape are licensed but Simscape_Electrical is 0
            testCase.verifyEqual(diag.status, 'BLOCKED_LICENSE');
            testCase.verifyTrue(any(contains(diag.missingRequirements, 'Simscape Electrical license')));
        end

        function testStatusInterpretationReadyWithOverrides(testCase)
            options = struct('quiet', true);
            options.overrides = struct( ...
                'simulinkInstalled', true, ...
                'simulinkLicensed', true, ...
                'simscapeInstalled', true, ...
                'simscapeLicensed', true, ...
                'simscapeElectricalInstalled', true, ...
                'simscapeElectricalLicensed', true, ...
                'modelBuildingAPIsAvailable', true, ...
                'simulationAPIsAvailable', true, ...
                'componentsAvailable', true);

            diag = checkSimulationCapabilities(options);
            testCase.verifyEqual(diag.status, 'READY');
            testCase.verifyEmpty(diag.missingRequirements);
            testCase.verifyEmpty(diag.unverifiedRequirements);
        end

        function testStatusInterpretationBlockedLicenseWithOverrides(testCase)
            options = struct('quiet', true);
            options.overrides = struct( ...
                'simulinkInstalled', true, ...
                'simulinkLicensed', true, ...
                'simscapeInstalled', true, ...
                'simscapeLicensed', true, ...
                'simscapeElectricalInstalled', true, ...
                'simscapeElectricalLicensed', false, ...
                'modelBuildingAPIsAvailable', true, ...
                'simulationAPIsAvailable', true, ...
                'componentsAvailable', true);

            diag = checkSimulationCapabilities(options);
            testCase.verifyEqual(diag.status, 'BLOCKED_LICENSE');
            testCase.verifyNotEmpty(diag.missingRequirements);
            testCase.verifyNotEmpty(diag.unverifiedRequirements);
        end

        function testStatusInterpretationMissingProductWithOverrides(testCase)
            options = struct('quiet', true);
            options.overrides = struct( ...
                'simulinkInstalled', false, ...
                'simulinkLicensed', false, ...
                'simscapeInstalled', true, ...
                'simscapeLicensed', true, ...
                'simscapeElectricalInstalled', true, ...
                'simscapeElectricalLicensed', true, ...
                'modelBuildingAPIsAvailable', true, ...
                'simulationAPIsAvailable', true, ...
                'componentsAvailable', true);

            diag = checkSimulationCapabilities(options);
            testCase.verifyEqual(diag.status, 'BLOCKED_MISSING_PRODUCT');
        end

        function testStatusInterpretationMissingComponentsWithOverrides(testCase)
            options = struct('quiet', true);
            options.overrides = struct( ...
                'simulinkInstalled', true, ...
                'simulinkLicensed', true, ...
                'simscapeInstalled', true, ...
                'simscapeLicensed', true, ...
                'simscapeElectricalInstalled', true, ...
                'simscapeElectricalLicensed', true, ...
                'modelBuildingAPIsAvailable', true, ...
                'simulationAPIsAvailable', true, ...
                'componentsAvailable', false);

            diag = checkSimulationCapabilities(options);
            testCase.verifyEqual(diag.status, 'BLOCKED_COMPONENT');
        end

        function testStatusInterpretationMissingApisWithOverrides(testCase)
            options = struct('quiet', true);
            options.overrides = struct( ...
                'simulinkInstalled', true, ...
                'simulinkLicensed', true, ...
                'simscapeInstalled', true, ...
                'simscapeLicensed', true, ...
                'simscapeElectricalInstalled', true, ...
                'simscapeElectricalLicensed', true, ...
                'modelBuildingAPIsAvailable', false, ...
                'simulationAPIsAvailable', true, ...
                'componentsAvailable', true);

            diag = checkSimulationCapabilities(options);
            testCase.verifyEqual(diag.status, 'NEEDS_VERIFICATION');
        end

    end

end

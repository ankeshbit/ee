classdef TestBreakerFailureScenario < matlab.unittest.TestCase

    methods (Test)

        function testNormalPrimaryClearing(testCase)
            [fault, zones, relays, breakers] = caseData();
            result = evaluateBreakerFailureScenario( ...
                fault, zones, relays, breakers, failure('normal', ''));
            testCase.verifyEqual(result.overallStatus, ...
                'CLEARED_BY_PRIMARY_PROTECTION');
            testCase.verifyTrue(result.primaryBreakerClears);
            testCase.verifyEqual(result.primaryClearingTime_s, ...
                result.primaryRelayOperatingTime_s + 0.1, 'AbsTol', 1e-12);
        end

        function testPrimaryFailureBackupClears(testCase)
            [fault, zones, relays, breakers] = caseData();
            result = evaluateBreakerFailureScenario( ...
                fault, zones, relays, breakers, failure('primary_failed', 'CB_B'));
            testCase.verifyEqual(result.overallStatus, ...
                'CLEARED_BY_BACKUP_PROTECTION');
            testCase.verifyEqual(result.backupClearingTime_s, ...
                result.backupRelayOperatingTime_s + 0.2, 'AbsTol', 1e-12);
            testCase.verifyEqual(result.relayCTI_s, ...
                result.backupRelayOperatingTime_s - ...
                result.primaryRelayOperatingTime_s, 'AbsTol', 1e-12);
        end

        function testBackupDoesNotPickUp(testCase)
            [fault, zones, relays, breakers] = caseData();
            relays(1).pickupCurrent_A = 1e6;
            fault.relayResults( ...
                strcmp({fault.relayResults.relayId}, 'R_1')).operates = false;
            fault.relayResults( ...
                strcmp({fault.relayResults.relayId}, 'R_1')).operatingTime_s = Inf;
            result = evaluateBreakerFailureScenario( ...
                fault, zones, relays, breakers, failure('failed', 'CB_B'));
            testCase.verifyEqual(result.overallStatus, ...
                'NOT_CLEARED_BY_MODELED_PROTECTION');
        end

        function testBothBreakersFailed(testCase)
            [fault, zones, relays, breakers] = caseData();
            result = evaluateBreakerFailureScenario( ...
                fault, zones, relays, breakers, failure('failed', 'CB_1'));
            result2 = evaluateBreakerFailureScenario( ...
                fault, zones, relays, breakers, failure('failed', 'CB_B'));
            testCase.verifyEqual(result.overallStatus, ...
                'CLEARED_BY_PRIMARY_PROTECTION');
            testCase.verifyEqual(result2.overallStatus, ...
                'CLEARED_BY_BACKUP_PROTECTION');
            failureBoth = failure('both_failed', 'CB_B');
            failureBoth.failedBreakerIds = {'CB_B', 'CB_1'};
            result3 = evaluateBreakerFailureScenario( ...
                fault, zones, relays, breakers, failureBoth);
            testCase.verifyEqual(result3.overallStatus, ...
                'NOT_CLEARED_BY_MODELED_PROTECTION');
        end

        function testDirectionalBlocksBackup(testCase)
            [fault, zones, relays, breakers] = caseData();
            scenario = failure('reverse', 'CB_B');
            scenario.directionalResults.R_1 = struct('status', 'reverse');
            result = evaluateBreakerFailureScenario( ...
                fault, zones, relays, breakers, scenario);
            testCase.verifyEqual(result.overallStatus, ...
                'NOT_CLEARED_BY_MODELED_PROTECTION');
            testCase.verifyEqual(result.directionalStatus, 'notApplicable');
        end

        function testOverlappingZonesAreAmbiguous(testCase)
            [fault, zones, relays, breakers] = caseData();
            zones(2) = zones(1);
            zones(2).id = 'ZONE_OVERLAP';
            result = evaluateBreakerFailureScenario( ...
                fault, zones, relays, breakers, failure('overlap', ''));
            testCase.verifyEqual(result.zoneStatus, 'overlap');
            testCase.verifyEqual(result.overallStatus, ...
                'NOT_CLEARED_BY_MODELED_PROTECTION');
        end

        function testSensitivityIntegratesFailureResults(testCase)
            network = createIllustrativeBranchedTransformerRadialNetwork();
            [~, ~, relays, breakers] = caseData();
            scenario = struct('id', 'B', 'faultedBus', 'BUS_B', ...
                'faultType', 'three phase', 'Zf_pu', 0);
            zones = struct('id', 'ZONE_B', ...
                'protectedElementType', 'branch', ...
                'protectedElementId', 'BR_2', ...
                'primaryRelayId', 'R_B', ...
                'backupRelayIds', {{'R_1'}}, 'minimumCTI_s', 0.1, ...
                'applicableFaultedBuses', {{'BUS_B'}});
            options.breakers = breakers;
            options.zones = zones;
            options.breakerFailureScenarios = failure('failure', 'CB_B');
            options.breakerFailureScenarios.scenarioId = 'B';
            study = runFaultSensitivityStudy(network, scenario, relays, ...
                [], options);
            testCase.verifyEqual(height(study.breakerFailureTable), 1);
            report = generateFaultSensitivityReport(study);
            testCase.verifyEqual(height(report.backupClearingOutcomes), 1);
        end

        function testZoneWithoutBackupRelaysReportsNoBackupProtection(testCase)
            [fault, zones, relays, breakers] = caseData();
            zones.backupRelayIds = {};
            failureScenario = failure('cb_b_failed', 'CB_B');
            result = evaluateBreakerFailureScenario( ...
                fault, zones, relays, breakers, failureScenario);
            testCase.verifyEqual(result.overallStatus, 'NO_BACKUP_PROTECTION');
            testCase.verifyTrue(contains(result.reason, 'no backup', 'IgnoreCase', true));
        end
    end
end

function [fault, zones, relays, breakers] = caseData()
network = createIllustrativeBranchedTransformerRadialNetwork();
relays = struct( ...
    'id', {'R_1', 'R_B'}, ...
    'measurementElementType', {'branch', 'branch'}, ...
    'measurementElementId', {'BR_1', 'BR_2'}, ...
    'measurementSide', {'from', 'from'}, ...
    'pickupCurrent_A', {2, 2}, 'TMS', {1, 1}, ...
    'curveType', {'Very Inverse', 'Very Inverse'}, ...
    'CTprimary_A', {800, 400}, 'CTsecondary_A', {5, 5});
scenario = struct('id', 'B', 'faultedBus', 'BUS_B', ...
    'faultType', 'three phase', 'Zf_pu', 0);
fault = runIntegratedFaultStudy(network, scenario, relays, []);
zones = struct('id', 'ZONE_B', 'protectedElementType', 'branch', ...
    'protectedElementId', 'BR_2', 'primaryRelayId', 'R_B', ...
    'backupRelayIds', {{'R_1'}}, 'minimumCTI_s', 0.1, ...
    'applicableFaultedBuses', {{'BUS_B'}});
breakers = struct( ...
    'id', {'CB_1', 'CB_B'}, 'relayId', {'R_1', 'R_B'}, ...
    'openingDelay_s', {0.2, 0.1}, ...
    'state', {'closed', 'closed'});
end

function value = failure(id, failedBreakerId)
value = struct('id', id, 'failedBreakerId', failedBreakerId);
end
